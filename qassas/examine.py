def t(key, lang):
    return T[key][lang]


def examine(case_dir, year=2026):
    """Run every relevant parser over a case folder and return structured results."""
    ev_dir = os.path.join(case_dir, "evidence") if os.path.isdir(os.path.join(case_dir, "evidence")) else case_dir
    out = {"tool": "qassas " + __version__, "case_dir": case_dir, "files": [], "findings": [], "events": []}
    mpath = os.path.join(case_dir, "manifest.json")
    if os.path.exists(mpath):
        with open(mpath, encoding="utf-8") as fh:
            out["manifest"] = hashing.verify_manifest(json.load(fh), ev_dir)
    cdir = os.path.join(case_dir, "custody")
    out["custody"] = {}
    if os.path.isdir(cdir):
        for name in sorted(os.listdir(cdir)):
            if name.endswith(".jsonl"):
                path = os.path.join(cdir, name)
                out["custody"][name] = custody.verify(custody.read(path))
                if name == "custody.jsonl":
                    out["events"] += timeline.from_custody(path, "custody/" + name)
    work = tempfile.mkdtemp(prefix="qassas-carve-")
    for v in signatures.scan(ev_dir):
        out["files"].append(v)
        path = os.path.join(ev_dir, v["path"])
        rel = v["path"]
        kind = v["detected"]
        try:
            if kind == "sqlite":
                h = browser.read_history(path)
                out["events"] += timeline.from_browser(path, rel)
                for d in h["downloads"]:
                    out["findings"].append({"key": "download", "args": [d["target_path"], d["tab_url"]], "source": rel, "time_utc": d["time_utc"]})
            elif kind == "lnk":
                info = lnk.parse(path)
                out["events"] += timeline.from_lnk(path, rel)
                out["findings"].append({"key": "lnk", "args": [info.get("local_base_path")], "source": rel,
                                        "time_utc": info.get("target_accessed_utc")})
            elif kind and kind.startswith("pcap"):
                with open(path, "rb") as fh:
                    res = pcap.analyse(fh.read())
                out["events"] += timeline.from_pcap(path, rel)
                for b in res["beacons"]:
                    out["findings"].append({"key": "beacon", "args": [b["interval_s"], b["target"], b["count"]], "source": rel,
                                            "time_utc": b["first_utc"], "severity": "high"})
                for h in res["http"]:
                    if h["method"] in ("POST", "PUT"):
                        out["findings"].append({"key": "upload", "args": [h["bytes"], h["method"], h["host"] or h["server"], h["path"]],
                                                "source": rel, "time_utc": h["time_utc"], "severity": "high"})
            elif kind == "jpeg":
                _photo(out, path, rel)
            elif kind == "pdf":
                _pdf(out, path, rel)
            elif kind is None and rel.endswith(".jsonl"):
                evs = logs.parse_windows_export(path)
                for e in evs:
                    desc = e["summary"]["en"] + (": " + (e.get("service") or e.get("process") or e.get("user") or ""))
                    out["events"].append(timeline.event(e["time_utc"], "windows", e["type"], desc, rel))
                for f in logs.findings(evs):
                    out["findings"].append({"key": "log_" + f["code"], "source": rel, "time_utc": f["time_utc"], "detail": f,
                                            "severity": f["severity"]})
            elif kind is None and "auth" in rel and rel.endswith(".log"):
                with open(path, encoding="utf-8") as fh:
                    evs = logs.parse_auth_log(fh.read(), year)
                out["events"] += timeline.from_auth_log(path, rel, year)
                for f in logs.findings(evs):
                    out["findings"].append({"key": "log_" + f["code"], "source": rel, "time_utc": f["time_utc"], "detail": f,
                                            "severity": f["severity"]})
            elif kind is None and rel.endswith((".img", ".dd", ".raw", ".bin")):
                with open(path, "rb") as fh:
                    data = fh.read()
                for item in carve.carve_bytes(data):
                    name = "%s_at_%d.%s" % (os.path.basename(rel), item["offset"], item["type"])
                    cpath = os.path.join(work, name)
                    with open(cpath, "wb") as fh:
                        fh.write(item["data"])
                    label = "%s @ %d" % (rel, item["offset"])
                    out["files"].append({"path": label, "detected": item["type"], "status": "carved", "sha256": item["sha256"]})
                    if item["type"] == "jpg":
                        _photo(out, cpath, label)
                    elif item["type"] == "pdf":
                        _pdf(out, cpath, label)
                sc = strings.scan(data, 6)
                for a in sc["arabic"]:
                    out["findings"].append({"key": "arabic", "args": [a["text"]], "source": "%s @ %d" % (rel, a["offset"])})
                if sc["indicators"]:
                    flat = sorted({x for vals in sc["indicators"].values() for x in vals})
                    out["findings"].append({"key": "ioc", "args": [", ".join(flat)], "source": rel})
        except (ValueError, OSError) as err:
            out["findings"].append({"key": "error", "args": [str(err)], "source": rel})
    out["events"] = timeline.sort(out["events"])
    out["findings"].sort(key=lambda f: f.get("time_utc") or "9999")
    return out


def _photo(out, path, rel):
    meta = metadata.extract(path)
    out["events"] += timeline.from_photo(path, rel)
    gps = meta.get("gps")
    if gps:
        area = gps.get("nearest_area") or {"en": "unknown area", "ar": "منطقة غير معروفة"}
        out["findings"].append({"key": "gps", "args": [area, gps["lat"], gps["lon"]], "source": rel,
                                "time_utc": None})


def _pdf(out, path, rel):
    meta = metadata.extract(path)
    out["events"] += timeline.from_pdf(path, rel)
    if meta.get("revisions", 1) > 1:
        dt = metadata.pdf_date(meta.get("moddate"))
        out["findings"].append({"key": "pdf_rev", "args": [meta["revisions"], iso(dt, KUWAIT) if dt else "?"], "source": rel,
                                "time_utc": iso(dt.astimezone(UTC)) if dt and dt.tzinfo else None})


def _finding_text(f, lang):
    if f["key"].startswith("log_"):
        code = f["key"][4:]
        text = logs.FINDING_TEXT.get(code, {}).get(lang, code)
        d = f.get("detail", {})
        bits = [x for x in (d.get("source_ip"), d.get("user"), d.get("command")) if x]
        return text + ((" (" + ", ".join(bits) + ")") if bits and lang == "en" else (" " + " ".join(bits) if bits else ""))
    if f["key"] == "error":
        return f["args"][0]
    args = list(f.get("args", []))
    if f["key"] == "gps":
        args[0] = args[0][lang]
    return t(f["key"], lang) % tuple(args)


def markdown(result, lang="en", limit=80):
    rtl = lang == "ar"
    lines = ["# " + t("title", lang), "", t("synthetic", lang) % __version__, ""]
    lines += ["## " + t("integrity", lang), ""]
    m = result.get("manifest")
    if m:
        lines.append("- " + t("manifest_ok" if m["passed"] else "manifest_bad", lang))
        for item in m["modified"]:
            lines.append("  - `%s`" % item["path"])
    for name, problems in result.get("custody", {}).items():
        state = t("custody_ok" if not problems else "custody_bad", lang)
        detail = ""
        if problems:
            detail = " " + " ".join("[#%s %s]" % (p["seq"], custody.EXPLAIN[p["code"]][lang]) for p in problems)
        lines.append("- `%s` %s%s" % (name, state, detail))
    lines += ["", "## " + t("files", lang), "", "| %s | %s | |" % (t("col_path", lang), t("col_type", lang)), "|---|---|---|"]
    for f in result["files"]:
        flag = t("mismatch", lang) if f.get("status") == "mismatch" else ""
        lines.append("| `%s` | %s | %s |" % (f["path"], f.get("detected") or "?", flag))
    lines += ["", "## " + t("findings", lang), ""]
    for f in result["findings"]:
        when = iso(parse_iso(f["time_utc"]), KUWAIT) if f.get("time_utc") else ""
        lines.append("- %s%s  \n  `%s`" % ((when + " ") if when else "", _finding_text(f, lang), f["source"]))
    lines += ["", "## " + t("timeline", lang), "", t("raw_note", lang), "",
              "| %s | %s | %s |" % (t("col_time", lang), t("col_source", lang), t("col_event", lang)), "|---|---|---|"]
    for e in timeline.localise(result["events"], KUWAIT)[:limit]:
        lines.append("| %s | %s | %s |" % (e["time"], e["source"], e["description"].replace("|", "/")))
    text = "\n".join(lines) + "\n"
    if rtl:
        text = '<div dir="rtl">\n\n' + text + "\n</div>\n"
    return text
